
# Oliot ovat instansseja jostain luokasta.
# Niillä voi olla sisäisiä muuttujia ja metodeja.
# Esimerkiksi merkkijono on oikeastaan olio:
"Hei maailma!".upper()
# Tässä tapauksessa kutsutaan merkkijono-olion "upper()" metodia.

# Myös sanakirja, lista, setti, tuple ja muut jonot ovat olioita:
{"nimi": "toni", "ikä": 29}.copy()
[1, 2, 4].remove(1)
{26, "hei", 67.6}.pop()
(7, 4, 2).index(7)
# Jokaiselle näistä löytyy metodeja (olion/luokan funktioita).

